import React, { useEffect, useRef, useState } from 'react';
import { TerminalMessage, TerminalSettings } from '../types';

interface TerminalProps {
  messages: TerminalMessage[];
  isLoading: boolean;
  settings?: TerminalSettings;
  onRetryLast?: () => void;
}

const DEFAULT_SETTINGS: TerminalSettings = {
  crtEffects: true,
  typewriterEffect: true,
  typewriterSpeed: 'fast',
  soundEffects: false,
  reducedMotion: false,
  maxTokens: 120,
  temperature: 0.7,
};

const ASCII_BANNER = `
  ___ _               _ _____               _             _     _   ___ 
 / __| |_  ___  ___ _| |_   _|__ _ _ _ __ _(_)_ _  __ _ _| |   /_\\ |_ _|
| (_ | ' \\/ _ \\(_-</ _\` || |/ -_) '_| '  \\| | ' \\/ _\` | | |  / _ \\ | | 
 \\___|_||_\\___//__/\\__,_||_|\\___|_| |_|_|_|_|_||_\\__,_|_|_| /_/ \\_\\___|
    ::: Hacktoberfest 2026 - Week 4: Ghost in the Machine :::
`;

export const Terminal: React.FC<TerminalProps> = ({
  messages,
  isLoading,
  settings = DEFAULT_SETTINGS,
  onRetryLast,
}) => {
  const terminalEndRef = useRef<HTMLDivElement>(null);
  const [copiedId, setCopiedId] = useState<string | null>(null);

  // Auto-scroll to bottom
  useEffect(() => {
    terminalEndRef.current?.scrollIntoView({
      behavior: settings.reducedMotion ? 'auto' : 'smooth',
    });
  }, [messages, isLoading, settings.reducedMotion]);

  const handleCopy = (id: string, text: string) => {
    navigator.clipboard.writeText(text).then(() => {
      setCopiedId(id);
      setTimeout(() => setCopiedId(null), 2000);
    }).catch(() => {});
  };

  return (
    <div
      className={`terminal-screen ${settings.crtEffects ? 'crt-effects-active' : ''}`}
      role="log"
      aria-live="polite"
      aria-label="Terminal conversation display"
    >
      <div className="terminal-content">
        <pre className="ascii-banner" aria-hidden="true">{ASCII_BANNER}</pre>

        <div className="welcome-banner">
          <p className="welcome-line">
            <span className="accent-ghost">[SPIRIT]</span> A haunted terminal awakened from cold silicon.
          </p>
          <p className="welcome-line secondary">
            Local open-weight intelligence (<span className="glow-text">Qwen2.5-0.5B-Instruct</span>) bound within memory address <span className="glow-text">0xDEADBEEF</span>.
          </p>
          <p className="welcome-line dim">
            Type <kbd className="terminal-kbd">help</kbd> for recognized incantations or speak freely to commune across the veil.
          </p>
        </div>

        <div className="messages-list">
          {messages.map((msg) => (
            <article key={msg.id} className={`message-item message-${msg.sender}`}>
              {msg.sender === 'user' && (
                <div className="user-message">
                  <span className="user-prompt-symbol" aria-hidden="true">&gt;</span>
                  <span className="user-text">{msg.text}</span>
                  <span className="timestamp" aria-label={`Sent at ${msg.timestamp.toLocaleTimeString()}`}>
                    {msg.timestamp.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' })}
                  </span>
                </div>
              )}

              {msg.sender === 'ghost' && (
                <div className="ghost-message">
                  <div className="message-header">
                    <span className="ghost-badge">
                      <span className="ghost-glyph" aria-hidden="true">👻</span>
                      <span>GHOST IN THE MACHINE</span>
                    </span>

                    {msg.metadata && (
                      <div className="metadata-bar">
                        {msg.metadata.mode === 'simulated' ? (
                          <span className="mode-badge mode-simulated" title="Executed via deterministic terminal handler">
                            SIMULATED
                          </span>
                        ) : (
                          <span className="mode-badge mode-local" title="Generated by local Qwen2.5-0.5B model on CPU">
                            LOCAL AI
                          </span>
                        )}

                        {msg.metadata.inference_ms !== undefined && (
                          <span className="meta-item" title="Inference latency">
                            ⏱ {msg.metadata.inference_ms.toFixed(1)} ms
                          </span>
                        )}

                        {msg.metadata.tokens_generated !== undefined && (
                          <span className="meta-item" title="Tokens generated">
                            ⚡ {msg.metadata.tokens_generated} tok
                          </span>
                        )}
                      </div>
                    )}

                    <button
                      type="button"
                      className="btn-copy"
                      onClick={() => handleCopy(msg.id, msg.text)}
                      aria-label="Copy response to clipboard"
                      title="Copy response"
                    >
                      {copiedId === msg.id ? '✓ Copied' : '📋 Copy'}
                    </button>
                  </div>

                  <div className="ghost-body">
                    <pre className="ghost-text">{msg.text}</pre>
                  </div>
                </div>
              )}

              {msg.sender === 'system' && (
                <div className="system-message">
                  <span className="system-icon" aria-hidden="true">⚙</span>
                  <span className="system-text">{msg.text}</span>
                </div>
              )}

              {msg.sender === 'error' && (
                <div className="error-message">
                  <div className="error-header">
                    <span className="error-icon" aria-hidden="true">⚠</span>
                    <strong>ETHEREAL INTERRUPT</strong>
                  </div>
                  <div className="error-body">{msg.text}</div>
                  {onRetryLast && (
                    <div className="error-actions">
                      <button type="button" className="retry-btn" onClick={onRetryLast}>
                        ⟳ Retry Last Incantation
                      </button>
                    </div>
                  )}
                </div>
              )}
            </article>
          ))}

          {isLoading && (
            <div className="thinking-indicator" role="status" aria-label="Ghost is thinking">
              <span className="spectral-spinner" aria-hidden="true" />
              <span className="thinking-text">Communing through the wires at 0xDEADBEEF</span>
              <span className="pulsing-dots" aria-hidden="true">...</span>
            </div>
          )}

          <div ref={terminalEndRef} />
        </div>
      </div>
    </div>
  );
};
